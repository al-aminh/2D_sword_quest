"""
# কী করছে: সিন আর্কিটেকচারের জন্য বেস অ্যাবস্ট্রাক্ট ক্লাস তৈরি করছে।
# কেন লাগছে: পলিমরফিজম ব্যবহার করে মেনু, গেমপ্লে ও পজ স্ক্রিন সহজে পরিবর্তন করার জন্য।
# real world-এ এটা কোথায় দেখা যায়: গেম ইঞ্জিন স্টেট মেশিন ও সিন ম্যানেজমেন্ট (যেমন Unity SceneManager / Godot SceneTree)।
"""

from abc import ABC, abstractmethod


class BaseScene(ABC):
    """
    # কী করছে: গেমের প্রতিটি আলাদা পর্দার জন্য একটি আদর্শ ইন্টারফেস প্রদান করে।
    # কেন লাগছে: গেমের কন্ট্রোল ফ্লো ঠিক রাখতে এবং সিনগুলোর মধ্যে সামঞ্জস্য বজায় রাখতে।
    # real world-এ এটা কোথায় দেখা যায়: স্টেট ডিজাইন প্যাটার্ন ও অবজেক্ট-ওরিয়েন্টেড গেম আর্কিটেকচার।
    """

    # কী করছে: সিনের অভ্যন্তরীণ ভ্যারিয়েবল ও স্টেট ইনিশিয়ালাইজ করে।
    # কেন লাগছে: প্রতিটি সিনের নিজস্ব অবজেক্ট ও লাইফসাইকেল সংরক্ষণ করার জন্য।
    # real world-এ এটা কোথায় দেখা যায়: গেম অবজেক্ট ইনিশিয়ালাইজেশন ও কনস্ট্রাক্টর প্যাটার্ন।
    def __init__(self, manager=None):
        self.manager = manager

    # কী করছে: সময়ের পার্থক্যের (dt) ভিত্তিতে সিনের অবজেক্ট ও অ্যানিমেশন আপডেট করে।
    # কেন লাগছে: ফ্রেমরেট স্বাধীন স্মুথ গতি নিশ্চিত করতে।
    # real world-এ এটা কোথায় দেখা যায়: ফিজিক্স এবং লজিক আপডেট লুপ (Tick / FixedUpdate)।
    @abstractmethod
    def update(self, dt: float) -> None:
        pass

    # কী করছে: বর্তমান সিনটির গ্রাফিক্স ওপেনজিএল দিয়ে স্ক্রিনে রেন্ডার করে।
    # কেন লাগছে: গ্রাফিক্স পাইপলাইনে অবজেক্টগুলো স্ক্রিনে প্রদর্শন করার জন্য।
    # real world-এ এটা কোথায় দেখা যায়: গ্রাফিক্স ড্র কল ও রেন্ডার পাস (Render Pipeline)।
    @abstractmethod
    def draw(self) -> None:
        pass

    # কী করছে: কিবোর্ড ইভেন্ট গ্রহণ করে নির্দিষ্ট অ্যাকশন ট্রিগার করে।
    # কেন লাগছে: ব্যবহারকারীর বোতাম প্রেস শনাক্ত করে ক্যারেক্টার ও ইউআই নিয়ন্ত্রণ করতে।
    # real world-এ এটা কোথায় দেখা যায়: ইনপুট হ্যান্ডলার সিস্টেম (Input Event Bus)।
    def on_key(self, key: str, is_down: bool) -> None:
        pass

    # কী করছে: মাউস ক্লিক এবং মুভমেন্ট ইভেন্ট গ্রহণ করে।
    # কেন লাগছে: মেনু বাটনে হোভার ও ক্লিকের আধুনিক ইন্টার‍্যাকশন তৈরি করতে।
    # real world-এ এটা কোথায় দেখা যায়: GUI ইভেন্ট ডিসপ্যাচার (UI Event System)।
    def on_mouse(self, x: float, y: float, button: int = -1, state: int = -1) -> None:
        pass
